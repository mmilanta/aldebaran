"""Regenerate the crossing study's data and standalone SVG. Standard library.

Run: python3 experiments/strangeness_figure.py
Fresh rational proofs supply the words for all three displayed drawings.
The drawn geometry is approximate; only the postprocessed counts are exact.
"""

import json
from math import cos, sin, pi

from strangeness import HERE, compute_case, from_word
from verify_smooth_atlas import read_atlas


def orbit(t, m, n):
    return 245*cos(t)+140*cos(m*t)+65*cos(n*t), 245*sin(t)+140*sin(m*t)-65*sin(n*t)


def generate():
    atlas = read_atlas(HERE/'smooth_atlas.json')
    cases = {(case['outer'], case['inner']): case for case in atlas['verified']}
    records = [compute_case(cases[pair])[0] for pair in ((2, 3), (4, 7), (6, 11))]
    js = "'use strict';\n\n// Generated by strangeness_figure.py from fresh smooth certificates.\n"
    js += '// Integer words and indices are exact. Times and coordinates only place the drawing.\n'
    js += 'const StrangenessData = '+json.dumps(records, indent=2)+';\n\n'
    js += "if (typeof module !== 'undefined' && module.exports) module.exports = StrangenessData;\n"
    (HERE/'strangeness_data.js').write_text(js)

    svg = ['<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="750" viewBox="0 0 1200 750" role="img" aria-labelledby="title desc">',
           '<title id="title">Three curves whose tangent makes zero net turns</title>',
           '<desc id="desc">Rhythms 2/3, 4/7, and 6/11 have strangeness 0, minus 1, and minus 1. Blue rings mark positive crossing weights; gold squares mark negative weights, starting at the rightmost point. All three curves have tangent index zero.</desc>',
           '<rect width="1200" height="750" fill="#101323"/>',
           '<g font-family="system-ui, sans-serif" fill="#f4f1e8">',
           '<text x="40" y="66" font-size="36" font-weight="700">Where the crossing remembers</text>',
           '<text x="40" y="105" font-size="19" fill="#c7c7d4">All three directions make zero net turns. Their crossings tell another story.</text>']
    for j, record in enumerate(records):
        m, n = record['outer'], record['inner']
        cx, cy, scale = 210+390*j, 355, .38
        def point(x, y):
            return f'{cx+scale*x:.5f},{cy-scale*y:.5f}'
        svg.append(f'<rect x="{30+390*j}" y="145" width="360" height="420" rx="16" fill="#0b0e1a" stroke="#383b50"/>')
        coordinates = [point(*orbit(2*pi*k/3600, m, n)) for k in range(3601)]
        svg.append('<path d="M'+' L'.join(coordinates)+'" fill="none" stroke="#c7c7d4" stroke-width="1.1"/>')
        result = from_word(record['word'], record['initial_index2'])
        marked = set()
        for (label, _), (x, y) in zip(record['word'], record['display_points']):
            if label in marked:
                continue
            marked.add(label)
            X, Y = cx+scale*x, cy-scale*y
            if result.weights[label] > 0:
                svg.append(f'<circle cx="{X:.5f}" cy="{Y:.5f}" r="3.8" fill="#0b0e1a" stroke="#9fc7eb" stroke-width="1.7"/>')
            else:
                svg.append(f'<rect x="{X-3.5:.5f}" y="{Y-3.5:.5f}" width="7" height="7" fill="#0b0e1a" stroke="#e8b66e" stroke-width="1.7"/>')
        svg.extend([f'<text x="{cx}" y="185" text-anchor="middle" font-size="25">{m} / {n}</text>',
                    f'<text x="{cx}" y="520" text-anchor="middle" font-size="20">Strangeness  {record["strangeness"]}</text>',
                    f'<text x="{cx}" y="548" text-anchor="middle" font-size="16" fill="#c7c7d4">{record["crossings"]} crossing'+('' if record['crossings'] == 1 else 's')+'</text>'])
    svg.extend(['<text x="40" y="615" font-size="18" fill="#c7c7d4">○ Blue: weight +1.  □ Gold: weight −1.  Start at the rightmost point.</text>',
                '<text x="40" y="650" font-size="18" fill="#c7c7d4">Multiply each weight by the crossing’s mean winding count, then add.</text>',
                '<text x="40" y="685" font-size="18" fill="#c7c7d4">Moving the start changes the weights. A starting-edge correction keeps strangeness fixed.</text>',
                '<text x="40" y="722" font-size="15" fill="#9999ae">Exact integer counts from rational smooth crossing certificates; the plotted paths use sampled, rounded coordinates.</text>',
                '</g></svg>'])
    (HERE/'strangeness.svg').write_text('\n'.join(svg)+'\n')
    print('Wrote strangeness_data.js and strangeness.svg from three fresh smooth proofs.')


if __name__ == '__main__':
    generate()
